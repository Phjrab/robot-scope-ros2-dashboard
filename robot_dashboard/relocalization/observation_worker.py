"""One private numerical subprocess; no ROS imports, publishers or network listener.

Only immutable reference preparation survives a timed-out request. Scan work is
single-flight, carries the parent's absolute monotonic deadline, and is discarded
on timeout. The parent still owns every input and completion validity check.
"""
from __future__ import annotations

import pickle
import select
import socket
import struct
import subprocess
import sys
import time

MAX_MESSAGE_BYTES = 4 * 1024 * 1024


class Channel:
    """Framed IPC over an inherited socket pair, never a public endpoint.

    Pickles are exclusively generated by this process and its own child. Partial
    preparation responses can be retained across deadline-bounded receives.
    """
    def __init__(self, sock):
        self.sock = sock
        self.sock.setblocking(False)
        self.buffer = bytearray()
        self.cancel_event = None

    def wait(self, *, writing=False, deadline=float('inf')):
        while True:
            if self.cancel_event is not None and self.cancel_event.is_set():
                raise InterruptedError('CANCELLED')
            remaining = deadline - time.monotonic()
            if remaining <= 0:
                raise TimeoutError
            timeout = min(remaining, .05) if self.cancel_event is not None else (None if remaining == float('inf') else remaining)
            ready = select.select([] if writing else [self.sock], [self.sock] if writing else [], [], timeout)
            if ready[1] if writing else ready[0]:
                return

    def send(self, value, deadline=float('inf')):
        payload = pickle.dumps(value, protocol=5)
        if len(payload) > MAX_MESSAGE_BYTES:
            raise ValueError('WORKER_MESSAGE_LIMIT')
        data = memoryview(struct.pack('!I', len(payload)) + payload)
        while data:
            self.wait(writing=True, deadline=deadline)
            try:
                sent = self.sock.send(data)
            except BlockingIOError:
                continue
            if not sent:
                raise EOFError
            data = data[sent:]

    def receive(self, deadline=float('inf')):
        while True:
            if time.monotonic() > deadline:
                raise TimeoutError
            if len(self.buffer) >= 4:
                size = struct.unpack('!I', self.buffer[:4])[0]
                if size > MAX_MESSAGE_BYTES:
                    raise ValueError('WORKER_MESSAGE_LIMIT')
                if len(self.buffer) >= size + 4:
                    payload = bytes(self.buffer[4:size + 4])
                    del self.buffer[:size + 4]
                    return pickle.loads(payload)
            self.wait(deadline=deadline)
            try:
                data = self.sock.recv(65536)
            except BlockingIOError:
                continue
            if not data:
                raise EOFError
            self.buffer.extend(data)


class RegistrationWorker:
    """Called only under ObservationAligner's single-flight lock."""
    def __init__(self):
        self.process = None
        self.channel = None
        self.phase = None
        self.key = None
        self.sequence = 0

    def _start(self):
        parent, child = socket.socketpair()
        try:
            self.process = subprocess.Popen(
                [sys.executable, '-m', __name__, str(child.fileno())], pass_fds=(child.fileno(),),
                stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
            self.channel = Channel(parent)
            self.phase = 'starting'
        except BaseException:
            parent.close()
            raise
        finally:
            child.close()

    def close(self):
        if self.channel is not None:
            self.channel.sock.close()
            self.channel = None
        if self.process is not None:
            if self.process.poll() is None:
                self.process.terminate()
            try:
                self.process.wait(timeout=.1)
            except subprocess.TimeoutExpired:
                self.process.kill()
                self.process.wait(timeout=.5)
            self.process = None
        self.phase = self.key = None

    def solve(self, key, reference, target_frame, points, frame, stamp_ns, seed, deadline, *, cancel_event=None, course_region=None):
        from .observation_alignment import ObservationAlignmentError
        try:
            if self.process is None:
                self._start()
            self.channel.cancel_event = cancel_event
            if self.process.poll() is not None:
                raise EOFError
            if self.phase == 'starting':
                if self.channel.receive(deadline) != ('ready',):
                    raise ValueError('WORKER_PROTOCOL')
                self.phase = 'ready'
            if self.phase == 'preparing':
                if self.channel.receive(deadline) != ('prepared', self.key):
                    raise ValueError('WORKER_PROTOCOL')
                self.phase = 'ready'
            if key != self.key:
                # A partial send cannot be resumed as a new request. Only a
                # fully sent immutable reference may continue preparing.
                self.phase = 'sending'
                self.channel.send(('prepare', key, reference, target_frame), deadline)
                self.key, self.phase = key, 'preparing'
                if self.channel.receive(deadline) != ('prepared', key):
                    raise ValueError('WORKER_PROTOCOL')
                self.phase = 'ready'
            self.sequence += 1
            token = self.sequence
            self.phase = 'solving'
            self.channel.send(('solve', key, token, points, frame, stamp_ns, seed, deadline, course_region), deadline)
            response = self.channel.receive(deadline)
            if response[:3] != ('result', key, token):
                raise ValueError('WORKER_PROTOCOL')
            self.phase = 'ready'
            if response[3] is not None:
                raise ObservationAlignmentError(response[3])
            return response[4]
        except TimeoutError as exc:
            if self.phase not in ('starting', 'preparing'):
                self.close()
            raise ObservationAlignmentError('COMPUTE_BUDGET_EXCEEDED') from exc
        except ObservationAlignmentError:
            raise
        except (OSError, EOFError, ValueError, pickle.UnpicklingError) as exc:
            self.close()
            raise ObservationAlignmentError('NUMERICAL_WORKER_UNAVAILABLE') from exc


def serve(fd):
    from .observation_alignment import ReferenceIndex, solve_prepared
    channel = Channel(socket.socket(fileno=fd))
    channel.send(('ready',))
    key = reference = grid = target_frame = None
    try:
        while True:
            message = channel.receive()
            if message[0] == 'prepare':
                _, key, reference, target_frame = message
                # Preparation is not a result; an over-budget parent request
                # fails and the next request must select a fresh scan and pose.
                grid = ReferenceIndex(reference)
                channel.send(('prepared', key))
            elif message[0] == 'solve':
                _, requested_key, token, points, frame, stamp_ns, seed, deadline, course_region = message
                error, result = None, None
                try:
                    if requested_key != key or time.monotonic() > deadline:
                        raise ValueError('COMPUTE_BUDGET_EXCEEDED')
                    result = solve_prepared(reference, grid, target_frame, points, frame, stamp_ns, seed, deadline,
                                            **({'course_region': course_region} if course_region else {}))
                except ValueError as exc:
                    error = str(exc)
                channel.send(('result', requested_key, token, error, result))
            else:
                raise ValueError('WORKER_PROTOCOL')
    except (EOFError, BrokenPipeError, ConnectionResetError):
        pass
    finally:
        channel.sock.close()


if __name__ == '__main__':
    serve(int(sys.argv[1]))
